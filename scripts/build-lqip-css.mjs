/**
 * Combines per-thumbnail LQIP data URIs (assets/portfolio/.lqip/*-lqip.css)
 * into a single css/lqip.css exposing --lqip-<name> custom properties.
 * The grid (js/manimate.js lqipStyle) references these vars for blur-up loading.
 *
 * Run: npm run build:lqip-css (also runs automatically after build:thumb-sizes)
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const LQIP_DIR = path.join(root, "assets", "portfolio", ".lqip");
const OUT_FILE = path.join(root, "css", "lqip.css");

if (!fs.existsSync(LQIP_DIR)) {
  console.log("No .lqip directory. Run build:thumb-sizes first.");
  process.exit(0);
}

const vars = [];
for (const file of fs.readdirSync(LQIP_DIR).filter((f) => f.endsWith("-lqip.css")).sort()) {
  const name = file.replace(/-lqip\.css$/, "");
  const css = fs.readFileSync(path.join(LQIP_DIR, file), "utf8");
  const match = css.match(/url\("([^"]+)"\)/);
  if (match) vars.push(`  --lqip-${name}: url("${match[1]}");`);
}

const banner = "/* Generated by scripts/build-lqip-css.mjs - do not edit by hand */";
fs.writeFileSync(OUT_FILE, `${banner}\n:root {\n${vars.join("\n")}\n}\n`);
console.log(`Wrote css/lqip.css (${vars.length} LQIP vars).`);
